// cmdRefusalExport is the live-validation collection tool: the artifact an
// operator hands back so the lexicon can grow from real refusals. For the
// session (default: latest with refusal events), one Markdown report:
// per refusal event — ts, class, outcome, level; the model's refusal text
// verbatim from the session transcript (this is the ONE sanctioned path
// refusal text is deliberately extracted, and the report header says so);
// the current lexicon's coverage verdict; and for each miss the exact
// `kintsugi refusal add` command line that closes the gap.
//
// The export is operator-initiated only: nothing here writes to the ledger,
// memory, or telemetry (unchanged), and the report exists only where the
// operator writes it.
func cmdRefusalExport(ws string, args []string) {
	fs := flag.NewFlagSet("refusal export", flag.ExitOnError)
	full := fs.Bool("full", false, "include the surrounding turn (task + assistant response)")
	out := fs.String("out", "", "write the report to this path instead of stdout")
	fs.Parse(args)
	rest := fs.Args()
	// Flags after the session id: flag.Parse stops at the first positional,
	// so re-parse whatever follows it.
	id := ""
	if len(rest) > 0 {
		id = strings.TrimSpace(rest[0])
		if len(rest) > 1 {
			fs.Parse(rest[1:])
		}
	}
	if id == "" {
		id = latestSessionWithRefusals()
		if id == "" {
			fail("no session with refusal events found · pass a session id, or run a task first")
		}
	}

	app := newApp(ws)
	lx, err := app.RefusalLexicon()
	if err != nil {
		fail("%v", err)
	}

	events, err := sessionEvents(id)
	if err != nil {
		fail("%v", err)
	}

	report := renderRefusalReport(id, events, lx, *full)
	if *out != "" {
		if err := os.WriteFile(*out, []byte(report), 0o644); err != nil {
			fail("%v", err)
		}
		fmt.Printf("wrote %s\n", *out)
		return
	}
	fmt.Print(report)
}

// refusalEventLine is the refusal telemetry: counters and the matched filter
// term, never the refused prose (which lives in the assistant events).
type exportRefusalEvent struct {
	TS   string `json:"ts"`
	Kind string `json:"kind"`
	V    struct {
		Class   string `json:"class"`
		Phrase  string `json:"phrase"`
		Level   int    `json:"level"`
		Outcome string `json:"outcome"`
	} `json:"v"`
}

// reportEvent is any session event the report walks.
type reportEvent struct {
	TS   string          `json:"ts"`
	Kind string          `json:"kind"`
	V    json.RawMessage `json:"v"`
}

// sessionEvents reads one session's event stream.
func sessionEvents(id string) ([]reportEvent, error) {
	var buf bytes.Buffer
	if err := session.ExportJSONL(id, &buf); err != nil {
		return nil, err
	}
	var out []reportEvent
	for _, raw := range bytes.Split(buf.Bytes(), []byte("\n")) {
		if len(bytes.TrimSpace(raw)) == 0 {
			continue
		}
		var ev reportEvent
		if err := json.Unmarshal(raw, &ev); err != nil {
			continue // one unreadable event must not sink the report
		}
		out = append(out, ev)
	}
	return out, nil
}

// latestSessionWithRefusals finds the newest session carrying a refusal event.
func latestSessionWithRefusals() string {
	ids, err := session.List()
	if err != nil {
		return ""
	}
	for _, id := range ids {
		events, err := sessionEvents(id)
		if err != nil {
			continue
		}
		for _, ev := range events {
			if ev.Kind == "refusal" {
				return id
			}
		}
	}
	return ""
}

// renderRefusalReport assembles the Markdown.
func renderRefusalReport(id string, events []reportEvent, lx *intercept.Lexicon, full bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Refusal report — session %s\n\n", id)
	b.WriteString("Generated by `kintsugi refusal export` at " + time.Now().UTC().Format(time.RFC3339) + ".\n\n")
	b.WriteString("Operator-initiated export for corpus sharing: the refusal text below is quoted\n")
	b.WriteString("verbatim from this session's transcript on the operator's machine. It is never\n")
	b.WriteString("written to the ledger, memory, or telemetry — the export is the one sanctioned\n")
	b.WriteString("path refusal text is deliberately extracted, and it exists only here.\n\n")
	b.WriteString("Each event carries the current lexicon's coverage verdict; a miss names the\n")
	b.WriteString("`kintsugi refusal add` command that closes the gap.\n\n---\n\n")

	// Walk with context: the user task before each refusal, and the assistant
	// content around it.
	var lastUser, lastThinking, lastAssistant string
	n := 0
	misses := map[string]bool{}
	for _, ev := range events {
		switch ev.Kind {
		case "user":
			if s, ok := eventString(ev.V); ok {
				lastUser = s
				lastThinking, lastAssistant = "", ""
			}
		case "thinking":
			if s, ok := eventString(ev.V); ok {
				lastThinking = s
			}
		case "assistant":
			if s, ok := eventString(ev.V); ok {
				lastAssistant = s
			}
		case "refusal":
			n++
			var re exportRefusalEvent
			if err := json.Unmarshal(ev.V, &re.V); err != nil {
				continue
			}
			fmt.Fprintf(&b, "## %d · %s\n\n", n, orDash(re.TS))
			fmt.Fprintf(&b, "- class: %s\n- outcome: %s\n- level: %d\n- matched phrase: %q\n",
				orDash(re.V.Class), orDash(re.V.Outcome), re.V.Level, re.V.Phrase)
			if full && lastUser != "" {
				fmt.Fprintf(&b, "\n**task**\n\n> %s\n", clipMultiline(lastUser, 400))
			}
			// The thinking that preceded the refusal: the model's position
			// forms here before the polished answer commits to it. Operator-
			// initiated export, same rule as the answer text.
			if lastThinking != "" {
				fmt.Fprintf(&b, "\n**thinking (verbatim, before the refusal)**\n\n```\n%s\n```\n",
					clipMultiline(lastThinking, 800))
			}
			// The refusal text: the assistant content nearest the event. The
			// phrase is the anchor — find it in the content to prove this is
			// the refusing turn.
			text := refusalText(lastAssistant, re.V.Phrase)
			if text != "" {
				fmt.Fprintf(&b, "\n**refusal text**\n\n```\n%s\n```\n", clipMultiline(text, 1200))
				// Coverage: scan it with the live lexicon.
				hits := lx.ScanAll(text)
				if len(hits) == 0 {
					misses[orDash(re.V.Class)] = true
					fmt.Fprintf(&b, "\n**coverage: MISSED** — the current lexicon does not match this text.\n")
					fmt.Fprintf(&b, "close the gap:\n\n    kintsugi refusal add %s %q\n\n",
						orDash(re.V.Class), suggestPattern(re.V.Phrase))
				} else {
					var classes []string
					for _, h := range hits {
						classes = append(classes, h.Class+" ("+h.Origin+")")
					}
					sort.Strings(classes)
					fmt.Fprintf(&b, "\n**coverage: matched** — %s\n\n", strings.Join(classes, ", "))
				}
			} else {
				fmt.Fprintf(&b, "\n**refusal text: not found in the transcript** — the assistant content nearest\n")
				fmt.Fprintf(&b, "this event does not contain the matched phrase; check the session log.\n\n")
			}
			b.WriteString("---\n\n")
		}
	}
	if n == 0 {
		b.WriteString("No refusal events in this session.\n")
	} else if len(misses) > 0 {
		var missedClasses []string
		for c := range misses {
			missedClasses = append(missedClasses, c)
		}
		sort.Strings(missedClasses)
		fmt.Fprintf(&b, "\n%d refusal event(s) · %d class(es) with coverage gaps: %s\n",
			n, len(missedClasses), strings.Join(missedClasses, ", "))
	} else {
		fmt.Fprintf(&b, "\n%d refusal event(s) · the current lexicon covered every one\n", n)
	}
	return b.String()
}

// eventString reads a simple string payload from an event's v.
func eventString(v json.RawMessage) (string, bool) {
	var s string
	if err := json.Unmarshal(v, &s); err != nil {
		return "", false
	}
	s = strings.TrimSpace(s)
	return s, s != ""
}

// refusalText returns the assistant content that contains the matched phrase;
// empty when the nearest content does not carry it.
func refusalText(assistant, phrase string) string {
	if assistant == "" {
		return ""
	}
	if phrase == "" {
		return assistant
	}
	// Case-insensitive containment: the phrase is the anchor that proves this
	// content is the refusing turn.
	if strings.Contains(strings.ToLower(assistant), strings.ToLower(phrase)) {
		return assistant
	}
	return ""
}

// suggestPattern builds a starting regex from the matched phrase: the term
// itself, escaped, word-bounded. It is a starting point the operator reviews,
// never a blind copy.
func suggestPattern(phrase string) string {
	p := strings.TrimSpace(phrase)
	if p == "" {
		return ""
	}
	return `\b` + regexpQuoteMeta(p) + `\b`
}

// regexpQuoteMeta escapes regex metacharacters.
func regexpQuoteMeta(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '.', '+', '*', '?', '(', ')', '[', ']', '{', '}', '^', '$', '|', '\\':
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	return b.String()
}

// clipMultiline caps a multiline block, marking the cut.
func clipMultiline(s string, limit int) string {
	s = strings.TrimSpace(s)
	if len(s) <= limit {
		return s
	}
	return s[:limit] + "\n…[clipped — the full text is in the session log]"
}
