// Package rules finds and imports rules that already live in a repository
// (DESIGN §8, I-26). Import is report-first: nothing enters the prompt stack
// until the operator runs `kintsugi rules import --apply`.
package rules

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	OutputRel   = ".kintsugi/rules/inherited.md"
	ManifestRel = ".kintsugi/rules/report.json"
)

type Source struct {
	Kind   string `json:"kind"`
	Path   string `json:"path"`
	Bytes  int    `json:"bytes"`
	SHA256 string `json:"sha256"`
}

type Report struct {
	Workspace string   `json:"workspace"`
	Sources   []Source `json:"sources"`
	Warnings  []string `json:"warnings,omitempty"`
	Output    string   `json:"output"`
	Applied   bool     `json:"applied"`
}

var detectors = []struct {
	kind string
	path string
	dir  bool
}{
	{kind: "agents-md", path: "AGENTS.md"},
	{kind: "cline", path: ".clinerules", dir: true},
	{kind: "cursor", path: ".cursor/rules", dir: true},
	{kind: "codex", path: ".codex/AGENTS.md"},
	{kind: "copilot", path: ".github/copilot-instructions.md"},
	{kind: "windsurf", path: ".windsurfrules"},
}

// Scan inspects a workspace and returns the import report. It never writes.
func Scan(ws string) (Report, error) {
	abs, err := filepath.Abs(ws)
	if err != nil {
		return Report{}, err
	}
	rep := Report{Workspace: abs, Output: OutputRel}
	seenHash := map[string]string{}
	for _, det := range detectors {
		full := filepath.Join(abs, det.path)
		info, err := os.Stat(full)
		if err != nil {
			continue
		}
		var files []string
		if info.IsDir() {
			if !det.dir {
				continue
			}
			err := filepath.WalkDir(full, func(p string, d os.DirEntry, err error) error {
				if err != nil {
					return nil
				}
				if d.IsDir() {
					return nil
				}
				if strings.HasSuffix(p, ".md") || strings.HasSuffix(p, ".mdc") || strings.HasSuffix(p, ".txt") {
					files = append(files, p)
				}
				return nil
			})
			if err != nil {
				return rep, err
			}
		} else {
			files = []string{full}
		}
		sort.Strings(files)
		for _, f := range files {
			data, err := os.ReadFile(f)
			if err != nil {
				rep.Warnings = append(rep.Warnings, "unreadable: "+f)
				continue
			}
			if len(data) == 0 {
				rep.Warnings = append(rep.Warnings, "empty: "+relPath(abs, f))
				continue
			}
			if len(data) > 256<<10 {
				rep.Warnings = append(rep.Warnings, "too large (skipped): "+relPath(abs, f))
				continue
			}
			sum := sha256.Sum256(data)
			hash := hex.EncodeToString(sum[:])
			rel := relPath(abs, f)
			if prev, ok := seenHash[hash]; ok {
				rep.Warnings = append(rep.Warnings, fmt.Sprintf("duplicate content: %s == %s", rel, prev))
				continue
			}
			seenHash[hash] = rel
			rep.Sources = append(rep.Sources, Source{Kind: det.kind, Path: rel, Bytes: len(data), SHA256: hash})
		}
	}
	return rep, nil
}

// Import scans, and when apply is true writes one inherited-rules file plus a
// manifest of source hashes. The compile step only reads the output file.
func Import(ws string, apply bool) (Report, error) {
	rep, err := Scan(ws)
	if err != nil || !apply || len(rep.Sources) == 0 {
		return rep, err
	}
	var b strings.Builder
	b.WriteString("<!-- generated by `kintsugi rules import --apply`; edit the sources, not this file -->\n")
	b.WriteString("# Inherited repository rules\n")
	for _, src := range rep.Sources {
		data, err := os.ReadFile(filepath.Join(rep.Workspace, src.Path))
		if err != nil {
			rep.Warnings = append(rep.Warnings, "read failed during import: "+src.Path)
			continue
		}
		fmt.Fprintf(&b, "\n## %s (%s, sha256:%s)\n\n", src.Path, src.Kind, short(src.SHA256))
		b.WriteString(strings.TrimRight(string(data), "\n"))
		b.WriteString("\n")
	}

	out := filepath.Join(rep.Workspace, OutputRel)
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return rep, err
	}
	if err := writeAtomic(out, []byte(b.String())); err != nil {
		return rep, err
	}
	rep.Applied = true
	manifest, _ := json.MarshalIndent(rep, "", "  ")
	if err := writeAtomic(filepath.Join(rep.Workspace, ManifestRel), manifest); err != nil {
		return rep, err
	}
	return rep, nil
}

// LoadInherited returns the applied rules text, or "" when nothing was
// imported. Callers append it to the behavior layer.
func LoadInherited(ws string) (text, path string) {
	p := filepath.Join(ws, OutputRel)
	b, err := os.ReadFile(p)
	if err != nil {
		return "", ""
	}
	return strings.TrimSpace(string(b)), p
}

func writeAtomic(path string, data []byte) error {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func relPath(root, p string) string {
	rel, err := filepath.Rel(root, p)
	if err != nil {
		return p
	}
	return filepath.ToSlash(rel)
}

func short(h string) string {
	if len(h) > 12 {
		return h[:12]
	}
	return h
}
